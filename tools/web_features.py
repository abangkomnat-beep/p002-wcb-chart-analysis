"""สวิตช์ที่ผูกกับ **ความสามารถของหน้าเว็บปลายทาง** ไม่ใช่รสนิยมการเขียน

ตอนนี้มีตัวเดียวคือ bullet และเหตุผลที่มันต้องเป็นสวิตช์ ไม่ใช่การแก้โค้ดตรง ๆ
อยู่ที่ว่ามันขึ้นกับของที่**เราสั่งเองไม่ได้**:

    ฟีดแบ็กหัวหน้า 2026-08-07 — `.an-body` ของเว็บมี CSS ให้แค่ h2/h3/p
    ลิสต์ `- ` กับตาราง `|...|` จึงขึ้นเว็บแล้วได้ของที่อ่านแทบไม่ได้บนมือถือ
    ⇒ แปลงเป็นย่อหน้าไปก่อน **เปิดกลับได้เมื่อทีมเว็บแจ้งว่าเพิ่ม CSS แล้วเท่านั้น**

    คำสั่งผู้ใช้ 2026-08-10 — หัวหน้าสั่งให้ใช้ bullet แต่**ไม่ได้พูดถึง CSS**
    ⇒ ทำใบตัวอย่างสองโหมดให้ผู้ใช้เลือก · **ผู้ใช้เลือกฉบับ bullet ⇒ เปิดสวิตช์**

**สถานะตอนนี้: เปิด** (สไตล์ A เป็นตัวเดียวที่เขียนรองรับสองโหมด — B/C ไม่มีลิสต์อยู่แล้ว)

🪤 **ของที่ยังไม่มีใครยืนยันคือ CSS** — ไม่ใช่การตัดสินใจ · เรื่องที่ยังต้องวัดเองคือ
`.an-body` มี rule ให้ `ul` แล้วจริงไหม (E23 ใน `EXTERNAL.md`) และวิธีวัดคือ
**เปิดหน้าบทจริงแล้วดูว่าลิสต์มีจุดนำและระยะย่อหน้าไหม** ไม่ใช่ถามแล้วเชื่อคำตอบ —
ปลายทางถอยกลับได้และเคยถอยมาแล้วสองครั้ง (ค่าคาดการณ์ปฏิทินหายกลับไปเป็น `null`)

**ถ้าหน้าจริงออกมาไม่มีจุดนำ:** กลับ `web_bullets_enabled` เป็น `false` ในแฟ้มนโยบาย
รอบผลิตถัดไปจะกลับเป็นร้อยแก้วทั้งบทเอง เนื้อความเท่าเดิมทุกตัวอักษร ไม่ต้องแก้โค้ด
และไม่ต้องรอใคร — นั่นคือเหตุผลทั้งหมดที่มันเป็นสวิตช์แทนการแก้ตัวนักเขียนตรง ๆ
"""

from __future__ import annotations

import json
from pathlib import Path

POLICY_PATH = Path(__file__).resolve().parents[1] / "config" / "publishing_policy.json"

# ค่าเริ่มต้นเมื่อแฟ้มนโยบายอ่านไม่ได้หรือไม่มีช่องนี้ — **ปิดเสมอ ไม่ตามค่าที่ตั้งไว้จริง**
# fail-closed: ไม่รู้ว่าเว็บรองรับไหม = ถือว่าไม่รองรับ เพราะฝั่งที่ผิดพลาดแล้วเสียหาย
# คือฝั่งที่ปล่อย bullet ขึ้นหน้าเว็บที่ไม่มี CSS ไม่ใช่ฝั่งที่เขียนเป็นย่อหน้าเกินจำเป็น
# (ค่านี้ไม่ใช่สถานะปัจจุบันของระบบ — สถานะจริงอยู่ในแฟ้มนโยบาย ตอนนี้เปิดอยู่)
BULLETS_DEFAULT = False


def bullets_enabled(policy_path: Path | None = None) -> bool:
    """หน้าเว็บปลายทางแสดง `ul` ได้แล้วหรือยัง

    อ่านใหม่ทุกครั้งโดยตั้งใจ ไม่แคช — เทสสลับค่าแล้ววัดผลได้ทันทีโดยไม่ต้อง reload
    โมดูล และรอบผลิตจริงวันละครั้งจึงไม่มีประเด็นเรื่องความเร็ว
    """
    path = policy_path or POLICY_PATH
    try:
        policy = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return BULLETS_DEFAULT
    value = policy.get("web_bullets_enabled", BULLETS_DEFAULT)
    return value is True


# fail-closed เหตุผลเดียวกับ bullet — ตาราง `|...|` บนหน้าเว็บที่ไม่มี CSS ให้
# `table/th/td` คืออักขระ | ดิบเต็มจอมือถือ ซึ่งแย่กว่าย่อหน้าธรรมดามาก
# (ค่านี้ไม่ใช่สถานะปัจจุบันของระบบ — สถานะจริงอยู่ในแฟ้มนโยบาย)
TABLES_DEFAULT = False


def tables_enabled(policy_path: Path | None = None) -> bool:
    """หน้าเว็บปลายทางแสดงตาราง markdown ได้แล้วหรือยัง

    🆕 08-11 ค่ำ — ผู้ใช้สั่งให้อินดิเคเตอร์รายวันของสไตล์ A เป็นตารางครบทุกตัว
    ⇒ เปิดสวิตช์ตามคำสั่ง · **ของที่ยังไม่มีใครยืนยันคือ CSS ของ `table` บนเว็บจริง**
    (เรื่องเดียวกับ bullet ตอน 08-10) — วิธีวัดคือเปิดหน้าบทจริงดูว่าตารางมีเส้น/ช่อง
    ไหม ถ้าออกมาเป็นอักขระ | ดิบ ให้กลับ `web_tables_enabled` เป็น false ในแฟ้มนโยบาย
    รอบผลิตถัดไปจะถอยเป็นร้อยแก้วเองโดยเนื้อความครบเท่าเดิม ไม่ต้องแก้โค้ด
    """
    path = policy_path or POLICY_PATH
    try:
        policy = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return TABLES_DEFAULT
    value = policy.get("web_tables_enabled", TABLES_DEFAULT)
    return value is True
