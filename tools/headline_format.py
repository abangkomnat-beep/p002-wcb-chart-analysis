def display_width(text: str) -> int:
    """ความกว้างที่ตามองเห็นจริง — สระบน/ล่างและวรรณยุกต์ไม่นับ

    **ทำไมต้องมีฟังก์ชันนี้ (วัดเจอ 2026-08-10):** เดิมงบความยาวพาดหัววัดด้วย `len()`
    ซึ่งนับ *จุดรหัส* ไม่ใช่ความกว้าง · ภาษาไทยวางสระกับวรรณยุกต์ซ้อนบนล่างของพยัญชนะ
    ตัวเหล่านั้นกินความกว้างศูนย์ แต่ `len()` นับเป็นตัวอักษรเต็มทุกตัว

        วิเคราะห์ทองคำวันนี้ 28 กุมภาพันธ์ 2026 — แนวโน้มราคาทอง XAU/USD
        len() = 64   ·   กว้างจริง = 55        ⇒ เกินจริงไป 9 (16%)

    Google ตัดพาดหัวตาม **ความกว้างเป็นพิกเซล** ไม่ได้ตัดตามจำนวนจุดรหัส การนับด้วย
    `len()` จึงเข้มเกินจริงกับภาษาไทยเสมอ และเข้มไม่เท่ากันในแต่ละคำ (คำที่สระเยอะ
    โดนลงโทษหนักกว่า) ⇒ ตัดสินใจผิดได้สองทาง: ตัดถ้อยคำดี ๆ ทิ้งเพราะคิดว่าเกิน
    หรือขยายงบทั้งระบบเพื่อแก้ปัญหาที่ไม่มีอยู่จริง

    วัดจริงตอนเปลี่ยนมาใช้ตัวนี้: พาดหัว 35 คู่ (7 สินทรัพย์ × 5 สไตล์) ที่เดือนยาวสุด
    `len()` บอกว่าเกินงบ 26 คู่ · ความกว้างจริงบอกว่า **ไม่เกินสักคู่** (สูงสุด 66/70)
    """
    return sum(0 if unicodedata.category(ch) == "Mn" else 1 for ch in text)


def thai_date(date_text: str, *, full_month: bool = False) -> str:
    """'2026-08-06' → '6 ส.ค. 2026' (หรือ '6 สิงหาคม 2026' เมื่อ full_month)

    ใช้ทั้งบนภาพและในบททุกสไตล์ ให้สะกดตรงกันหมด — **เดือนไทย ปี ค.ศ.**
    (ปี ค.ศ. ตามคำสั่งหัวหน้า 2026-08-11 · เหตุผลอยู่หัวไฟล์)
    """
    year, month, day = date_text.split("-")
    table = MONTH_FULL if full_month else MONTH_ABBR
    return f"{int(day)} {table[int(month) - 1]} {int(year)}"


def seo_name(asset: str) -> str:
    """คำเรียกสินทรัพย์ที่ใช้ในพาดหัว — คนละช่องกับ `thai_name` ที่ใช้ในเนื้อบท"""
    profile = wcb_source.profile_for(asset)
    return profile.get("seo_name") or profile["thai_name"]


def seo_h1_name(asset: str) -> str:
    """ชื่อในส่วนหน้าของ H1 — ตามสเปกบางตัว **ไม่ตรงกับชื่อใน Title**

    เกิดจาก WTI (โภคภัณฑ์ §2 · เพิ่ม 08-11): Title ใช้ "น้ำมันดิบ" แต่ H1 ใช้
    "น้ำมันดิบ WTI" — ลอกทีละตัวอักษรทั้งคู่ · สินทรัพย์ที่สเปกให้ชื่อเดียว
    ไม่ต้องมีช่อง `seo_h1_name` แล้วจะได้ชื่อเดียวกับ Title ตามเดิม
    """
    profile = wcb_source.profile_for(asset)
    return profile.get("seo_h1_name") or seo_name(asset)


def seo_tail(asset: str) -> str:
    """หางคงที่ของ Title tag ต่อสินทรัพย์ — ช่องคำค้น ต้องนิ่ง"""
    profile = wcb_source.profile_for(asset)
    return profile.get("seo_tail") or f"แนวโน้มราคา {profile['symbol']}"


def _thai_letter(ch: str) -> bool:
    return THAI_FIRST <= ch <= THAI_LAST


def _pad(name: str) -> str:
    """เว้นวรรครอบชื่อเฉพาะด้านที่ติดอักษรที่ไม่ใช่ไทย

    ภาษาไทยเขียนติดกันไม่มีเว้นวรรค แต่พอเอา ticker ละตินมาแปะติดคำไทยจะอ่านไม่ออก
    สเปกของหัวหน้าเขียนไว้ทั้งสองแบบในเอกสารเดียวกัน และต่างกันตรงชนิดอักษรพอดี:

        วิเคราะห์ทองคำวันนี้        ← ชื่อไทยล้วน ติดกันหมด
        วิเคราะห์ EUR/USD วันนี้     ← ชื่อละติน เว้นสองข้าง
        วิเคราะห์หุ้น NVIDIA วันนี้   ← ขึ้นต้นไทย ลงท้ายละติน เว้นข้างเดียว

    ⇒ กฎเดียวครอบทั้งสามเคส: ดูอักษรตัวแรกกับตัวสุดท้ายของชื่อ ไม่ต้องลงทะเบียนเอง
    (ลงทะเบียนมือแปลว่าวันที่เพิ่มสินทรัพย์ตัวใหม่แล้วลืม จะได้ 'วิเคราะห์SOLวันนี้')
    """
    if not name:
        return name
    lead = "" if _thai_letter(name[0]) else " "
    trail = "" if _thai_letter(name[-1]) else " "
    return f"{lead}{name}{trail}"


def prefix(asset: str, date_text: str, *, full_month: bool, for_h1: bool = False,
           wrap_date: bool = False) -> str:
    """ส่วนหน้าที่ทุกสไตล์ใช้ร่วมกัน — จุดเดียวที่ประกอบ ชื่อ + คำว่า 'วันนี้' + วันที่

    `for_h1=True` ใช้ชื่อของช่อง H1 (`seo_h1_name`) — ต่างจาก Title เฉพาะสินทรัพย์
    ที่สเปกให้ชื่อสองตัว เช่น WTI (ดู `seo_h1_name`)

    `wrap_date=True` คร่อมวันที่ด้วยวงเล็บ — **สไตล์ H เท่านั้น ตามใบที่ผู้ใช้สั่ง
    2026-08-14** (`วิเคราะห์ทองคำวันนี้ (14 ส.ค. 2026) — …`) · สไตล์อื่นยังเป็นรูป
    เดิมตามสเปกของหัวหน้า 08-10 ⇒ ตัวเลือกอยู่ที่นี่จุดเดียว ไม่ให้ใครไปต่อวงเล็บเอง
    ที่ปลายทาง เพราะด่านวันที่ใน `consistency_gate` อ่านวันที่จากพาดหัวโดยตรง
    """
    name = seo_h1_name(asset) if for_h1 else seo_name(asset)
    date_out = thai_date(date_text, full_month=full_month)
    return (PREFIX_TEMPLATE.format(name=_pad(name))
            + " " + (f"({date_out})" if wrap_date else date_out))


def build(asset: str, date_text: str, tail: str, *, full_month: bool,
          for_h1: bool = False, wrap_date: bool = False) -> str:
    """ประกอบพาดหัวเต็มรูป — ตัวเดียวที่ต่อ `—` ให้ทั้งระบบ"""
    return (prefix(asset, date_text, full_month=full_month, for_h1=for_h1,
                   wrap_date=wrap_date)
            + SEPARATOR + str(tail).strip())


def title(asset: str, date_text: str, tail: str | None = None) -> str:
    """Title tag — เดือนเต็ม · หางคงที่ตามทะเบียน เว้นแต่ผู้เรียกส่งหางของสไตล์มาเอง"""
    return build(asset, date_text, tail or seo_tail(asset), full_month=True)


def weekly_title(asset: str, week_start: str, week_end: str,
                 tail: str | None = None) -> str:
    """Style D Title tag: weekly wording plus a complete Monday--Friday range."""
    name = _pad(seo_name(asset))
    return (f"วิเคราะห์{name}รายสัปดาห์ วันที่ {weekly_thai_range(week_start, week_end)}"
            + SEPARATOR + str(tail or seo_tail(asset)).strip())


def h1(asset: str, date_text: str, tail: str, *, wrap_date: bool = False) -> str:
    """พาดหัวในบท — เดือนย่อ · หางเล่าสาระของวันนั้น · ชื่อตามช่อง H1 ของสเปก"""
    return build(asset, date_text, tail, full_month=False, for_h1=True,
                 wrap_date=wrap_date)


def same_headline(title_text: str, h1_text: str) -> bool:
    """Title กับ H1 ซ้ำกันไหม — เทียบแบบไม่สนช่องว่างส่วนเกิน

    เงื่อนไขของหัวหน้า: สองอันต้องไม่เหมือนกัน · ตัวที่เรียกใช้จริงคือด่านของสไตล์ D/E
    (`title_equals_h1`) ⇒ เขียนหางชนกันเมื่อไหร่ บทไม่ออก ไม่ใช่ออกไปแล้วค่อยรู้ทีหลัง
    """
    return " ".join(title_text.split()) == " ".join(h1_text.split())
