def date_thai(event_at: str) -> str:
    """"ศุกร์ 7 ส.ค." — ชื่อวันกับวันที่มาจากฟิลด์ `at` ตัวเดียวกัน ไม่ได้คำนวณเทียบวันนี้

    คืนค่าว่างเมื่ออ่าน `at` ไม่ออก ตามกติกาเดิมของไฟล์นี้ (ค่าไม่มี = ผู้เรียกตัดวลีทิ้ง)
    """
    stamp = str(event_at or "")[:10]
    try:
        day = date.fromisoformat(stamp)
    except ValueError:
        return ""
    return f"{THAI_WEEKDAY[day.weekday()]} {day.day} {THAI_MONTH_ABBR[day.month - 1]}"


def clock(event_at: str) -> str:
    """เวลา HH:MM จากฟิลด์ `at` — คืนค่าว่างเมื่อรูปแบบไม่ตรง

    🐞 เดิมตัด `[11:16]` ดิบ ๆ โดยไม่ตรวจ ⇒ `at` รูปแบบใหม่ที่ต้นทางเปลี่ยนมาเมื่อไหร่
    บทจะพิมพ์เศษตัวอักษรออกมาเป็น "เวลา ี่ยัง น." โดยไม่มีอะไรฟ้อง (เจอตอนเขียนเทส
    ของข้อ A-3 · 2026-08-09) — ค่าที่อ่านไม่ออกต้องเงียบ ไม่ใช่เดาว่าตำแหน่งเดิมยังใช่
    """
    found = _CLOCK.match(str(event_at or "")[11:16])
    return found.group(0) if found else ""


