def _thai_code(registry: dict, code, what: str) -> str:
    if code in (None, ""):
        return ""
    try:
        return registry[code]
    except KeyError:
        raise ValueError(f"{what}ที่ไม่รู้จักจากปลายทาง: {code!r}") from None


