def trend_code(evidence: dict) -> str:
    """up/dn/fl เท่านั้น — ระบบนำเข้าของเว็บปฏิเสธค่าอื่นทุกค่า รวมทั้งคำไทย"""
    indicators = evidence["daily"]["indicators"]
    spot = float(evidence["quote"]["price"])
    fast = (indicators.get("SMA20") or {}).get("value")
    slow = (indicators.get("SMA50") or {}).get("value")
    if fast is None or slow is None:
        return "fl"
    if spot > fast and spot > slow:
        return "up"
    if spot < fast and spot < slow:
        return "dn"
    return "fl"


def _pivot_group(evidence: dict, timeframe: str) -> list[float]:
    """จุดหมุนของกรอบเวลาเดียว — ไม่ปนกับกรอบอื่น"""
    group = ((_tf_block(evidence, timeframe) or {}).get("pivots")) or {}
    return [float(group[key]) for key in wcb_source.PIVOT_KEYS if group.get(key) is not None]


def _levels_by_frame(evidence: dict) -> tuple[list[float], list[float], dict[str, str]]:
    """แนวรับ/แนวต้าน + **กรอบเวลาที่แต่ละฝั่งมาจาก** (ผู้ใช้อนุมัติ 2026-08-06)

    กติกาสองข้อที่ต้องอยู่ด้วยกัน ขาดข้อใดข้อหนึ่งก็กลับไปเป็นบั๊กเดิม:

    1. **ฝั่งเดียวกันต้องมาจากกรอบเดียวกันทั้งชุด** — ของเดิมเทจุดหมุนทั้งสี่กรอบรวมกอง
       เดียวแล้วเรียงตามระยะห่างจากราคา ⇒ จุดหมุนกรอบเล็กชนะทุกครั้งเพราะอยู่ใกล้ราคา
       กว่าเสมอ บทรายวันจึงได้ด่านที่แคบกว่าที่ราคาเดินจริงหลายสิบเท่า และบางครั้งด่าน
       ที่หนึ่งกับที่สองห่างกันไม่ถึงหนึ่งในหมื่นของราคา (BTC 2026-08-05: ห่างกัน 3.14
       ดอลลาร์จากราคา 64,317 ⇒ อ่านแล้วไม่ได้ข้อมูลอะไร)

    2. **ไล่จากกรอบใหญ่ไปเล็ก แยกกันสองฝั่ง** — ไม่ใช่เลือกกรอบเดียวให้ทั้งสองฝั่ง
       เพราะวันที่ราคาวิ่งแรง จุดหมุนรายวัน (คำนวณจากแท่งเมื่อวาน) จะถูกทะลุหมดทุกชั้น
       ฝั่งนั้นจึงว่างเปล่า ⇒ ถ้าบังคับรายวันล้วน บททองกับ NVDA ของ 2026-08-05 จะ
       **ไม่มีหัวข้อฝั่งบนเลย** ซึ่งเป็นวันที่คนอ่านต้องการด่านฝั่งบนมากที่สุด
       (วัดจริงก่อนอนุมัติ — ดู `01-CC/Output/2026-08-06_บทตัวอย่างข้อ5-*.html`)

    **ไม่มีเกณฑ์ตัวเลขใหม่และไม่กรองด่านที่อยู่ชิดราคาทิ้ง** — การทิ้ง evidence จริง
    เพราะมันไม่สวยคือสิ่งที่ระบบนี้ห้าม สิ่งที่ทำแทนคือกำกับกรอบเวลาให้คนอ่านตัดสินเอง
    """
    spot = float(evidence["quote"]["price"])
    digits = profile_of(evidence)["decimals"]

    def keep(values: list[float]) -> list[float]:
        """ปัดตามทศนิยมของสินทรัพย์แล้วตัดค่าซ้ำ โดยคงลำดับใกล้ราคาไปไกล"""
        return list(dict.fromkeys(round(v, digits) for v in values))

    below: list[float] = []
    above: list[float] = []
    source: dict[str, str] = {}
    for timeframe in TF_ORDER:
        values = _pivot_group(evidence, timeframe)
        if not below:
            found = sorted((v for v in values if v < spot), reverse=True)
            if found:
                below, source["below"] = keep(found), timeframe
        if not above:
            found = sorted(v for v in values if v >= spot)
            if found:
                above, source["above"] = keep(found), timeframe
    return below, above, source


def _sorted_levels(evidence: dict) -> tuple[list[float], list[float]]:
    """แนวรับ/แนวต้าน แยกด้วยราคาปัจจุบัน ไม่ใช่ด้วยชื่อ r/s

    pivot ที่ชื่อ r1 อาจอยู่ใต้ราคาไปแล้วเมื่อราคาทะลุขึ้นมา การเรียกมันว่าแนวต้าน
    ต่อไปคือการอ่านผิด · จัดกลุ่มตามตำแหน่งจริงเทียบราคาจึงถูกเสมอ

    หน้าร้านของ `_levels_by_frame` สำหรับจุดเรียกที่ไม่ต้องรู้ว่าค่ามาจากกรอบไหน
    (เช่นหมุดกราฟกับย่อหน้าเงื่อนไขของสไตล์ B) — ค่าที่ได้เป็นชุดเดียวกันเสมอ
    ⇒ เส้นบนกราฟตรงกับตัวเลขในบทโดยไม่ต้องประสานเพิ่ม
    """
    below, above, _ = _levels_by_frame(evidence)
    return below, above


def _distinct_lines(values: list[float], limit: int, evidence: dict) -> list[str]:
    """pivot คนละ TF ที่ปัดแล้วชนกันต้องเหลือเส้นเดียว

    เส้นซ้ำบนกราฟไม่ได้ให้ข้อมูลเพิ่ม แต่ทำให้ผู้อ่านนึกว่ามีสองด่านที่ระดับเดียวกัน

    ความหยาบของการปัดมาจากทะเบียนสินทรัพย์ ไม่ใช่ `int()` ตายตัวอย่างเดิม —
    EUR/USD ทุก pivot ปัดเป็นจำนวนเต็มแล้วได้ "1" หมดทุกเส้น หมุดกราฟจึงออกมาเป็น
    `[[chart:1day|s=1|r=1]]` ทั้งฝั่งรับและฝั่งต้าน (2026-08-05)
    """
    digits = profile_of(evidence)["levels"]
    seen: list[str] = []
    for value in values:
        text = str(int(round(value))) if digits == 0 else f"{value:.{digits}f}"
        if text not in seen:
            seen.append(text)
        if len(seen) == limit:
            break
    return seen


def chart_marker(evidence: dict, timeframe: str, *, supports=3, resistances=3) -> str:
    # ค่าตั้งต้น 3/3 (เดิม 2/2) — ผู้ใช้ทัก 08-11 ค่ำ: บทไล่ 3 ด่านต่อฝั่ง
    # แต่ภาพตีเส้นแค่ 2 · ภาพวาดเส้นตามหมุดนี้ (`chart_public_renderer.pin_levels`)
    # แก้ที่นี่จุดเดียว เส้นบนภาพครบตามบทเอง
    below, above = _sorted_levels(evidence)
    parts = [f"chart:{timeframe}"]
    lower = _distinct_lines(below, supports, evidence)
    upper = _distinct_lines(above, resistances, evidence)
    if lower:
        parts.append("s=" + ",".join(lower))
    if upper:
        parts.append("r=" + ",".join(upper))
    return "[[" + "|".join(parts) + "]]"


def _streak(bars: list[dict], key: str) -> int:
    """จำนวนแท่งท้ายสุดที่ค่า key ไล่สูงขึ้นต่อเนื่อง — นับจากแท่งจริงเท่านั้น

    ⚠️ ปลายทางส่งแท่งมาด้วยชื่อช่องสั้น (`o` `h` `l` `c`) ไม่ใช่ `open`/`high`/`low`/`close`
    เดิมฟังก์ชันนี้ถูกเรียกด้วย `"high"`/`"low"` ⇒ `KeyError` ทุกครั้ง แล้ว `except` กลืนไว้
    คืนค่า 1 เสมอ ⇒ **ย่อหน้านับแท่งของสไตล์ B ไม่เคยขึ้นเลยสักครั้ง** ทั้งที่สเปกระบุว่า
    การนับแท่งที่ตรวจย้อนได้คือจุดขายของสไตล์นั้น (พบ 2026-08-05)

    ตอนนี้ช่องที่ไม่รู้จักจะโยนออกไป ไม่กลืนเงียบ — ให้ล้มดังกว่าให้ย่อหน้าหายไปเฉย ๆ
    """
    if key not in BAR_FIELDS:
        raise KeyError(f"ช่องแท่งราคา {key!r} ไม่มีในก้อนของ WCB — มีแค่ {sorted(BAR_FIELDS)}")
    count = 1
    for index in range(len(bars) - 1, 0, -1):
        try:
            current = float(bars[index][key])
            previous = float(bars[index - 1][key])
        except (KeyError, TypeError, ValueError):
            break
        if current > previous:
            count += 1
        else:
            break
    return count


def _average_stack(evidence: dict, names: tuple[str, ...]) -> list[str]:
    """ตำแหน่งราคาเทียบเส้นค่าเฉลี่ย — **ยุบเส้นที่ค่าปัดมาชนกันให้เหลือบรรทัดเดียว**

    ปลายทางส่งค่าที่เป็นราคามาเป็นทศนิยมสองตำแหน่งทุกสินทรัพย์ ⇒ กับ EUR/USD
    ที่ระดับ 1.15 เส้น 20 วันกับ 50 วันออกมาเป็น 1.14 เท่ากันเป๊ะ

    ถ้าพิมพ์เรียงกันตรง ๆ จะได้ "เหนือเส้น SMA20 ที่ 1.14000 · เหนือเส้น SMA50 ที่ 1.14000"
    ซึ่งอ่านแล้วเหมือนสองด่านคนละที่ ทั้งที่เป็นตัวเลขเดียวกัน — **เป็นการนำเสนอที่ทำให้
    เข้าใจผิด แม้ทุกตัวเลขจะตรงหลักฐาน** · ยุบเป็น "เหนือเส้น SMA20 และ SMA50 ที่ 1.14000"
    ได้ความจริงเท่าเดิมแต่ไม่หลอกตา และบอกโดยนัยว่าสองเส้นนี้แยกกันไม่ออกที่ความละเอียดนี้

    ทองกับบิทคอยน์ไม่เคยชนกันอยู่แล้ว ฟังก์ชันนี้จึงไม่เปลี่ยนอะไรของสองตัวนั้น
    """
    spot = float(evidence["quote"]["price"])
    indicators = evidence["daily"]["indicators"]
    grouped: list[tuple[str, list[str]]] = []
    for name in names:
        value = (indicators.get(name) or {}).get("value")
        if value is None:
            continue
        text = price(value, evidence)
        side = "เหนือ" if spot > float(value) else "ใต้"
        key = f"{side}|{text}"
        if grouped and grouped[-1][0] == key:
            grouped[-1][1].append(name)
        else:
            grouped.append((key, [name]))
    stack = []
    for key, members in grouped:
        side, text = key.split("|")
        stack.append(f"{side}เส้น {' และ '.join(members)} ที่ {text}")
    return stack


def listing(lead: str, items: list[str], *, tail: str = "") -> list[str]:
    """ชุดรายการที่ออกได้สองหน้าตา — bullet เมื่อเว็บรองรับ · ร้อยแก้วเมื่อยังไม่รองรับ

    **เนื้อความต้องเท่ากันเป๊ะทั้งสองโหมด** เปลี่ยนแค่เครื่องหมายคั่น — ไม่งั้นสวิตช์
    ตัวเดียวจะกลายเป็นบทความคนละฉบับ แล้วสิ่งที่หัวหน้าตรวจผ่านจะไม่ใช่สิ่งที่ขึ้นเว็บ
    ⇒ ด่านตัวเลขและด่านคำต้องห้ามให้ผลเดียวกันทั้งสองโหมดโดยอัตโนมัติ

    โหมดร้อยแก้วคั่นด้วย ` · ` ตามที่บทสายนี้ใช้มาตลอด (ไม่ใช่ลูกน้ำ เพราะตัวเลข
    ในบทมีลูกน้ำคั่นหลักพันอยู่แล้ว อ่านปนกันทันที)
    """
    if not items:
        return []
    if web_features.bullets_enabled():
        # บรรทัดว่างคั่นหัวเรื่องกับลิสต์เสมอ — parser ฝั่งเว็บที่ไม่ยอมให้ลิสต์
        # แทรกกลางย่อหน้าจะกลืนบรรทัด `- ` เข้าไปเป็นข้อความธรรมดาถ้าไม่มีบรรทัดว่าง
        head = [lead.rstrip(), ""] if lead else []
        body = [f"- {item}" for item in items]
        return head + body + (["", tail] if tail else [])
    prose = (f"{lead} " if lead else "") + " · ".join(items)
    return [prose + (f" {tail}" if tail else "")]


